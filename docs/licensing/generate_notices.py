#!/usr/bin/env python3
"""Generate a local macOS dependency inventory using installed cargo-deny.

No downloads beyond Cargo's locked metadata resolution; no license selection
or legal approval. When a published crate archive omits standalone license
files, bundled SPDX standard texts are included for its locked license IDs.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SPDX_DIR = Path(__file__).resolve().parent / "spdx"
SPDX_IDS = ("Apache-2.0", "MIT", "Zlib")


def cargo_json(*args):
    return json.loads(subprocess.check_output(
        ["perl", "-e", "alarm shift; exec @ARGV", "300", "cargo", *args],
        cwd=ROOT, timeout=305,
    ))


def synthesized_notices(package):
    expr = package.get("license") or ""
    identifiers = re.sub(r"\b(?:AND|OR)\b|[()/]", " ", expr).split()
    if not identifiers or any(identifier not in SPDX_IDS for identifier in identifiers):
        return []
    # Metadata authors are not inferred copyright holders. Keep SPDX placeholders
    # verbatim; the fallback supplies license terms, not missing upstream attribution.
    return [(f"SPDX:{identifier}", normalize_text(
        (SPDX_DIR / f"{identifier}.txt").read_text(encoding="utf-8")))
        for identifier in SPDX_IDS if identifier in identifiers]


def normalize_text(text):
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


def notice_files(package):
    manifest = Path(package["manifest_path"])
    root = manifest.parent
    candidates = list(root.iterdir())
    for folder in ("licenses", "LICENSES"):
        if (root / folder).is_dir():
            candidates.extend((root / folder).rglob("*"))
    paths = {p for p in candidates if p.is_file() and (
        p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"))
        or p.parent.name in ("licenses", "LICENSES"))}
    if package.get("license_file"):
        paths.add(root / package["license_file"])
    found = [(str(p.relative_to(root)), normalize_text(p.read_text(encoding="utf-8")))
             for p in sorted(paths)]
    if not found and manifest.is_file():
        return synthesized_notices(package)
    return found


def render(metadata, inventory, lock_hash):
    members = set(metadata["workspace_members"])
    packages = {}
    for package in metadata["packages"]:
        packages.setdefault((package["name"], package["version"]), []).append(package)
    lines = ["# Third-party notices (generated)", "",
             "Generated by `python3 docs/licensing/generate_notices.py` using installed cargo-deny and locked Cargo metadata.",
             f"Cargo.lock SHA-256: `{lock_hash}`.", "",
             "Scope: deny.toml's macOS targets, including build/dev dependencies; this is a conservative inventory, not a linked-binary SBOM.",
             "License expressions are upstream declarations, not a choice of license or approval of every alternative.",
             "Original available LICENSE/NOTICE texts follow, deduplicated by SHA-256; copyright notices are preserved.",
             "Line endings and trailing whitespace are normalized before hashing and rendering; license wording is unchanged.",
             "When a crate archive omits standalone license files, SPDX License List v3.27.0 standard texts (`SPDX:<ID>`) are included for declared license IDs.",
             "SPDX fallbacks preserve template placeholders and do not recover missing upstream copyright notices; attribution still requires release review.",
             "Krill is licensed under Apache-2.0 (MK-077).", "",
             "## Bundled UI & Provider Icons (`crates/krill-app/src/ui/icons.rs`)", "",
             "- Utility icons (`TRASH_SVG`, `LAYOUT_DASHBOARD_SVG`, `FOLDER_PLUS_SVG`, `CROSSHAIR_SVG`, `KANBAN_SVG`, `SHIELD_SVG`, `ARROW_LEFT_SVG`, `ARROW_RIGHT_SVG`, `SLIDERS_HORIZONTAL_SVG`, `MOON_SVG`, `GIT_BRANCH_SVG`, `CALENDAR_CLOCK_SVG`, `SQUARE_TERMINAL_SVG`, `ROTATE_CCW_SVG`, `PIN_SVG`, `PIN_OFF_SVG`, `SPARKLES_SVG`, `TERMINAL_SVG`, `BELL_SVG`, `WORKFLOW_SVG`, `PLUG_SVG`, `SERVER_SVG`, `PANELS_TOP_LEFT_SVG`, `HISTORY_SVG`, `MEMORY_STICK_SVG`, `TRIANGLE_ALERT_SVG`, `CIRCLE_ARROW_UP_SVG`): Lucide Icons (`ISC` / Feather `MIT`, see `gpui-kit-assets` notice text below).",
             "- Provider and agent brand marks (`CLAUDE_SVG`, `OPENAI_SVG`, `ANTIGRAVITY_SVG`, `ANTIGRAVITY_CREST_SVG`, `OPENCODE_SVG`, `OPENCODE_CORE_SVG`, `CURSOR_SVG`, `CURSOR_TOP_SVG`): SVG path geometry adapted from Orca (`Copyright (c) 2026 Lovecast Inc.`, MIT License) and official provider silhouettes for nominal identification of supported external AI coding agents and account providers (`Claude` / Anthropic PBC, `Codex` / OpenAI OpCo, LLC, `Antigravity` / Google LLC, `Cursor` / Anysphere, Inc., `OpenCode` / Anomaly Innovations, Inc.). All third-party product names, logos, and brands are trademarks of their respective owners; their appearance in Krill is for identification only and does not imply endorsement or affiliation.", "",
             "| Package | Declared license | Repository | Notice texts |",
             "| --- | --- | --- | --- |"]
    texts = {}
    missing = []
    count = 0
    for key in sorted(inventory):
        name, version, _ = key.split(" ", 2)
        matches = packages.get((name, version), [])
        if len(matches) != 1:
            raise ValueError(f"ambiguous/missing metadata for {key}")
        package = matches[0]
        if package["id"] in members:
            continue
        count += 1
        links = []
        for filename, body in notice_files(package):
            digest = hashlib.sha256(body.encode()).hexdigest()
            texts.setdefault(digest, body)
            links.append(f"[{filename}](#text-{digest})")
        if not links:
            missing.append(f"{name} {version}")
        expression = (package.get("license") or "UNDECLARED").replace("|", "\\|")
        repo = package.get("repository") or "—"
        lines.append(f"| {name} {version} | {expression} | {repo} | "
                     + (", ".join(links) or "**UPSTREAM TEXT MISSING**") + " |")
    lines.extend(["", f"Inventory: {count} packages; {len(missing)} packages without notice texts.", "",
                  "## Packages without notice texts", ""])
    lines.extend([f"- {item}" for item in missing] or ["None (all packages have upstream or standard SPDX notice texts)."])
    for digest, body in sorted(texts.items()):
        lines.extend(["", f'<a id="text-{digest}"></a>', f"## Text {digest}", "", "````", body.rstrip(), "````"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed notices differ")
    args = parser.parse_args()
    metadata = cargo_json("metadata", "--locked", "--format-version", "1")
    inventory = cargo_json("deny", "--locked", "list", "--format", "json", "--layout", "crate")
    content = render(metadata, inventory, hashlib.sha256((ROOT / "Cargo.lock").read_bytes()).hexdigest())
    dest = ROOT / "THIRD_PARTY_NOTICES.md"
    if args.check:
        if not dest.is_file() or dest.read_text() != content:
            raise SystemExit("THIRD_PARTY_NOTICES.md is stale; regenerate it")
        print("third-party notice inventory is current")
    else:
        dest.write_text(content)
        print(f"generated {dest.name}")


if __name__ == "__main__":
    main()
