//! Lightweight ko/en catalog (MK-094). Every key requires both translations.
//! Only settings owns the active language; views resolve keys when rendering.

use serde::{Deserialize, Serialize};
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    #[default]
    Ko,
    En,
}

#[derive(Debug)]
pub struct Locale(Language);
impl gpui::Global for Locale {}

static ACTIVE: AtomicU8 = AtomicU8::new(0);

pub fn language() -> Language {
    if ACTIVE.load(Ordering::Relaxed) == 0 {
        Language::Ko
    } else {
        Language::En
    }
}

/// Called on the UI thread before refreshing windows and native menus.
pub(crate) fn set_language(language: Language, cx: &mut gpui::App) {
    ACTIVE.store(u8::from(language == Language::En), Ordering::Relaxed);
    if cx
        .try_global::<Locale>()
        .is_none_or(|old| old.0 != language)
    {
        cx.set_global(Locale(language));
    }
    gpui_component::set_locale(match language {
        Language::Ko => "ko",
        Language::En => "en",
    });
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Message {
    pub id: &'static str,
    ko: &'static str,
    en: &'static str,
}

impl Message {
    pub fn in_language(self, language: Language) -> &'static str {
        match language {
            Language::Ko => self.ko,
            Language::En => self.en,
        }
    }

    pub fn get(self) -> &'static str {
        self.in_language(language())
    }

    /// "Mac"·"Finder"·"Dock"처럼 macOS 이름이 박힌 문구. macOS 밖에서는 `other`(카탈로그 `other_os`)를 쓴다(OWE-834).
    #[must_use]
    pub const fn mac_or(self, other: Self) -> Self {
        if cfg!(target_os = "macos") {
            self
        } else {
            other
        }
    }

    /// Named substitutions permit translators to reorder fields. Replacement values are
    /// inserted once, so braces in paths, errors, or terminal text stay literal.
    pub fn format(self, args: &[(&str, &str)]) -> String {
        let template = self.get();
        let mut result = String::new();
        let mut rest = template;
        while let Some((prefix, field)) = rest.split_once('{') {
            result.push_str(prefix);
            let Some((name, tail)) = field.split_once('}') else {
                result.push('{');
                result.push_str(field);
                return result;
            };
            if let Some((_, value)) = args.iter().find(|(key, _)| *key == name) {
                result.push_str(value);
            } else {
                result.push('{');
                result.push_str(name);
                result.push('}');
            }
            rest = tail;
        }
        result.push_str(rest);
        result
    }
}

// Keep catalog results static and allocation-free on every platform. Windows/Linux hints
// follow keys::windows_keys, including Shift/Alt needed to preserve terminal controls.
macro_rules! platform_text {
    ($mac:literal, $other:literal) => {
        if cfg!(target_os = "macos") {
            $mac
        } else {
            $other
        }
    };
}

macro_rules! catalog {
    ($($group:ident { $($key:ident $( [$id:literal] )? => ($ko:expr, $en:expr)),* $(,)? })*) => {
        pub mod catalog {
            $(pub mod $group {
                $(pub const $key: super::super::Message = super::super::Message {
                    id: catalog!(@id $group, $key $(, $id)?), ko: $ko, en: $en,
                };)*
            })*
        }
        pub const ALL: &[Message] = &[$($(catalog::$group::$key),*),*];
    };
    (@id $group:ident, $key:ident, $id:literal) => { $id };
    (@id $group:ident, $key:ident) => { concat!(stringify!($group), ".", stringify!($key)) };
}

